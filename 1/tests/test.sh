EXE="../../task1.exe"

if [ ! -f "$EXE" ]; then
    echo "Ошибка: $EXE не найден."
    exit 1
fi

pass=0
fail=0

run_test() {
    local description="$1"
    local expected="$2"
    shift 2
    local args=("$@")

    output=$("$EXE" "${args[@]}" 2>&1)
    if [ "$output" == "$expected" ]; then
        echo "[PASS] $description"
        pass=$((pass+1))
    else
        echo "[FAIL] $description"
        echo "  Аргументы: ${args[*]}"
        echo "  Ожидалось: $expected"
        echo "  Получено:   $output"
        fail=$((fail+1))
    fi
}

